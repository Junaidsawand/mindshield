"""
MindShield Backend — Analysis Pydantic Schemas.

Defines the request and response models for the ``/api/v1/analyze``
endpoint. Pydantic v2 enforces type constraints and runs validators
at parse time, providing automatic HTTP 422 responses for invalid input.

Contract (matches Flutter's Dio expectations):

    POST /api/v1/analyze
    Content-Type: application/json
    {
        "message": "URGENT: Your bank account...",
        "sender": "+447911123456"    // optional
    }

    200 OK
    {
        "success": true,
        "message": "Analysis complete",
        "data": {
            "label": "phishing",
            "threat_level": "dangerous",
            "confidence": 0.97,
            "explanation": "...",
            "model_version": "placeholder-v0",
            "is_placeholder": true,
            "predicted_at": "2026-08-03T10:30:00Z"
        }
    }
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Annotated, Literal

from pydantic import BaseModel, Field, field_validator

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

_MIN_MESSAGE_LENGTH = 3
_MAX_MESSAGE_LENGTH = 2_000  # Practical SMS/MMS upper bound


# ---------------------------------------------------------------------------
# Request Schema
# ---------------------------------------------------------------------------


class AnalysisRequest(BaseModel):
    """Request body for SMS analysis endpoint.

    Attributes:
        message: The raw SMS body text to classify.
        sender:  Optional sender identifier (phone number or name).
                 Not used in classification in Phase 2.1, stored for
                 future contextual analysis.
    """

    message: Annotated[
        str,
        Field(
            min_length=_MIN_MESSAGE_LENGTH,
            max_length=_MAX_MESSAGE_LENGTH,
            description=(
                "Raw SMS body text to analyse. "
                f"Must be between {_MIN_MESSAGE_LENGTH} and "
                f"{_MAX_MESSAGE_LENGTH} characters."
            ),
            examples=["URGENT: Your bank account has been suspended. Click now!"],
        ),
    ]
    sender: Annotated[
        str | None,
        Field(
            default=None,
            max_length=50,
            description="Optional sender identifier (phone number or display name).",
            examples=["+447911123456"],
        ),
    ] = None

    @field_validator("message", mode="before")
    @classmethod
    def strip_and_validate_message(cls, v: str) -> str:
        """Strip surrounding whitespace from message text.

        After stripping, Pydantic's min_length constraint will correctly
        reject messages that are only whitespace.
        """
        if not isinstance(v, str):
            raise ValueError("message must be a string")
        return v.strip()

    model_config = {
        "json_schema_extra": {
            "example": {
                "message": (
                    "URGENT: Your bank account has been suspended. "
                    "Click here to restore access: http://fake-bank.example.com"
                ),
                "sender": "+447911123456",
            }
        }
    }


# ---------------------------------------------------------------------------
# Response Schema
# ---------------------------------------------------------------------------

ThreatLevel = Literal["safe", "suspicious", "dangerous"]


class AnalysisResult(BaseModel):
    """Classification result returned by the analysis endpoint.

    Attributes:
        label:         Raw classifier output (e.g. "phishing", "safe").
        threat_level:  Normalised severity bucket.
        confidence:    Model confidence score in [0.0, 1.0].
        explanation:   Human-readable rationale for the classification.
        model_version: Version of the model that produced this result.
        is_placeholder: True when response was generated by the stub
                       loader (Phase 2.1). Clients can use this flag
                       to display a disclaimer to the user.
        predicted_at:  UTC timestamp of the inference.
    """

    label: str = Field(
        description="Raw classifier label (e.g. 'safe', 'phishing', 'spam')."
    )
    threat_level: ThreatLevel = Field(
        description="Normalised threat severity: safe | suspicious | dangerous."
    )
    confidence: float = Field(
        ge=0.0,
        le=1.0,
        description="Model confidence score in the range [0.0, 1.0].",
    )
    explanation: str = Field(
        description="Human-readable explanation of the classification decision."
    )
    model_version: str = Field(
        description="Identifier of the model version used for inference."
    )
    is_placeholder: bool = Field(
        default=False,
        description=(
            "True when this result was produced by the Phase 2.1 "
            "placeholder — not a real prediction."
        ),
    )
    predicted_at: datetime = Field(
        default_factory=lambda: datetime.now(tz=timezone.utc),
        description="UTC datetime when inference was performed.",
    )

    model_config = {
        "json_schema_extra": {
            "example": {
                "label": "safe",
                "threat_level": "safe",
                "confidence": 0.5,
                "explanation": ("Phase 2.1 placeholder — no real model is loaded."),
                "model_version": "placeholder-v0",
                "is_placeholder": True,
                "predicted_at": "2026-08-03T10:30:00Z",
            }
        },
    }
